# Extracts the essentials from dump.dmp: the exception code, the crash address and the call stack.
#
#   python read_crash_dump.py <path to dump.dmp>
#
# No debugger is needed for this: minidump is a documented format, and three streams inside it
# are enough for us (module list, thread list, exception record). The stack is unwound crudely -
# we scan the stack memory and take values that fall inside loaded modules. That way return addresses
# show up among the garbage, and the call picture is good enough to find the culprit.
import struct
import sys

DUMP = sys.argv[1]

THREAD_LIST, MODULE_LIST, MEMORY_LIST, EXCEPTION_STREAM, MEMORY64_LIST = 3, 4, 5, 6, 9

# Windows exception codes that actually occur when the game crashes
CODES = {
    0xC0000005: "ACCESS_VIOLATION — обращение по недопустимому адресу",
    0xC0000006: "IN_PAGE_ERROR — не удалось подгрузить страницу памяти",
    0xC000001D: "ILLEGAL_INSTRUCTION",
    0xC0000025: "NONCONTINUABLE_EXCEPTION",
    0xC0000026: "INVALID_DISPOSITION",
    0xC000008C: "ARRAY_BOUNDS_EXCEEDED",
    0xC0000094: "INTEGER_DIVIDE_BY_ZERO",
    0xC0000096: "PRIV_INSTRUCTION",
    0xC00000FD: "STACK_OVERFLOW — переполнение стека",
    0xC0000409: "STACK_BUFFER_OVERRUN / быстрый выход (__fastfail)",
    0xC0000374: "HEAP_CORRUPTION — повреждена куча",
    0xE0434352: "исключение .NET",
    0x80000003: "BREAKPOINT",
}

ACCESS = {0: "чтение", 1: "запись", 8: "выполнение (DEP)"}

data = open(DUMP, "rb").read()


def u(fmt, off):
    return struct.unpack_from(fmt, data, off)


def read_string(rva):
    (length,) = u("<I", rva)
    return data[rva + 4:rva + 4 + length].decode("utf-16-le", "replace")


signature, version, n_streams, dir_rva = u("<IIII", 0)
if signature != 0x504D444D:
    raise SystemExit("это не minidump")

streams = {}
for i in range(n_streams):
    stream_type, size, rva = u("<III", dir_rva + i * 12)
    streams[stream_type] = (size, rva)


def modules():
    size, rva = streams[MODULE_LIST]
    (count,) = u("<I", rva)
    out = []
    for i in range(count):
        base = rva + 4 + i * 108
        base_of_image, size_of_image, _chk, _ts, name_rva = u("<QIIII", base)
        out.append((base_of_image, size_of_image, read_string(name_rva)))
    out.sort()
    return out


MODULES = modules()


def module_of(addr):
    for base, size, name in MODULES:
        if base <= addr < base + size:
            return name.rsplit("\\", 1)[-1], addr - base
    return None, 0


def module_path(short_name):
    for _base, _size, name in MODULES:
        if name.rsplit("\\", 1)[-1] == short_name:
            return name
    return None


# Function names are taken from the export table of the file itself on disk: in the Bannerlord engine it is
# called by the TaleWorlds.Engine.AutoGenerated layer, so there are many exports and the nearest one below is
# usually the right function. No debug symbols are required for this.
_EXPORTS = {}


def exports_of(short_name):
    if short_name in _EXPORTS:
        return _EXPORTS[short_name]
    table = []
    path = module_path(short_name)
    try:
        pe = open(path, "rb").read()
        (e_lfanew,) = struct.unpack_from("<I", pe, 0x3C)
        n_sections, = struct.unpack_from("<H", pe, e_lfanew + 6)
        opt = e_lfanew + 24
        (magic,) = struct.unpack_from("<H", pe, opt)
        dir_off = opt + (112 if magic == 0x20B else 96)
        exp_rva, exp_size = struct.unpack_from("<II", pe, dir_off)

        sections = []
        for i in range(n_sections):
            off = opt + struct.unpack_from("<H", pe, e_lfanew + 20)[0] + i * 40
            v_size, v_addr, r_size, r_ptr = struct.unpack_from("<IIII", pe, off + 8)
            sections.append((v_addr, max(v_size, r_size), r_ptr))

        def to_file(rva):
            for v_addr, v_size, r_ptr in sections:
                if v_addr <= rva < v_addr + v_size:
                    return r_ptr + (rva - v_addr)
            return None

        if exp_rva and exp_size:
            base = to_file(exp_rva)
            n_names = struct.unpack_from("<I", pe, base + 24)[0]
            addr_funcs, addr_names, addr_ords = struct.unpack_from("<III", pe, base + 28)
            for i in range(n_names):
                name_rva = struct.unpack_from("<I", pe, to_file(addr_names) + i * 4)[0]
                ordinal = struct.unpack_from("<H", pe, to_file(addr_ords) + i * 2)[0]
                func_rva = struct.unpack_from("<I", pe, to_file(addr_funcs) + ordinal * 4)[0]
                end = pe.index(b"\0", to_file(name_rva))
                table.append((func_rva, pe[to_file(name_rva):end].decode("ascii", "replace")))
            table.sort()
    except Exception:
        table = []
    _EXPORTS[short_name] = table
    return table


def symbol_for(short_name, offset):
    table = exports_of(short_name)
    best = None
    for rva, name in table:
        if rva <= offset:
            best = (rva, name)
        else:
            break
    if best is None:
        return ""
    return "  %s + 0x%X" % (best[1], offset - best[0])


# Memory map: both the normal list and the 64-bit one (a full dump uses the second)
def memory_ranges():
    ranges = []
    if MEMORY_LIST in streams:
        _size, rva = streams[MEMORY_LIST]
        (count,) = u("<I", rva)
        for i in range(count):
            start, dsize, drva = u("<QII", rva + 4 + i * 16)
            ranges.append((start, dsize, drva))
    if MEMORY64_LIST in streams:
        _size, rva = streams[MEMORY64_LIST]
        count, base_rva = u("<QQ", rva)
        offset = base_rva
        for i in range(count):
            start, dsize = u("<QQ", rva + 16 + i * 16)
            ranges.append((start, dsize, offset))
            offset += dsize
    ranges.sort()
    return ranges


RANGES = memory_ranges()


def read_memory(addr, length):
    for start, size, rva in RANGES:
        if start <= addr < start + size:
            take = min(length, start + size - addr)
            off = rva + (addr - start)
            return data[off:off + take]
    return b""


print("=" * 78)
size, rva = streams[EXCEPTION_STREAM]
thread_id, _pad = u("<II", rva)
code, flags, _nested, address, n_params = u("<IIQQI", rva + 8)
params = [u("<Q", rva + 8 + 32 + i * 8)[0] for i in range(min(n_params, 15))]

print("Код исключения: 0x%08X  %s" % (code, CODES.get(code, "неизвестный")))
name, offset = module_of(address)
if name:
    print("Упало в:        %s + 0x%X" % (name, offset))
else:
    print("Упало по адресу 0x%016X (вне загруженных модулей)" % address)
    below = [m for m in MODULES if m[0] <= address]
    above = [m for m in MODULES if m[0] > address]
    if below:
        b, s, n = below[-1]
        print("                ближайший модуль ниже:  0x%016X..0x%016X  %s"
              % (b, b + s, n.rsplit("\\", 1)[-1]))
    if above:
        b, s, n = above[0]
        print("                ближайший модуль выше:  0x%016X            %s"
              % (b, n.rsplit("\\", 1)[-1]))
    print("                => это код, сгенерированный на лету (JIT .NET): управляемое исключение")

if code in (0xC0000005, 0xC0000006) and len(params) >= 2:
    kind = ACCESS.get(params[0], "операция %d" % params[0])
    bad = params[1]
    note = ""
    if bad < 0x10000:
        note = "  <- нулевой указатель" if bad < 0x1000 else "  <- почти нулевой указатель (поле объекта)"
    print("Операция:       %s по адресу 0x%X%s" % (kind, bad, note))

ctx_size, ctx_rva = u("<II", rva + 8 + 152)
rsp, rip = u("<Q", ctx_rva + 0x98)[0], u("<Q", ctx_rva + 0xF8)[0]
print("Поток:          %d,  RIP 0x%X,  RSP 0x%X" % (thread_id, rip, rsp))

# Stack bounds of the crashed thread - from the thread list
stack_top = 0
_size, trva = streams[THREAD_LIST]
(tcount,) = u("<I", trva)
for i in range(tcount):
    tid = u("<I", trva + 4 + i * 48)[0]
    if tid == thread_id:
        start, dsize, _drva = u("<QII", trva + 4 + i * 48 + 16)
        stack_top = start + dsize
        break

print("=" * 78)
print("Стек вызовов (обратные адреса, найденные в памяти стека):")
if not stack_top or stack_top <= rsp:
    stack_top = rsp + 0x20000
raw = read_memory(rsp, min(stack_top - rsp, 0x40000))
if not raw:
    print("  память стека в дамп не попала")
else:
    seen, shown = set(), 0
    for off in range(0, len(raw) - 8, 8):
        (value,) = struct.unpack_from("<Q", raw, off)
        mod, delta = module_of(value)
        if not mod or (mod, delta) in seen:
            continue
        seen.add((mod, delta))
        print("  %3d  %-34s + 0x%-8X%s" % (shown, mod, delta, symbol_for(mod, delta)))
        shown += 1
        if shown >= 40:
            break

print("=" * 78)
print("Модули игры рядом с местом падения:")
for base, msize, mname in MODULES:
    short = mname.rsplit("\\", 1)[-1]
    if base <= rip < base + msize or short.lower().startswith(("taleworlds", "rgl", "d3d", "nv", "ig")):
        mark = "  <== здесь упало" if base <= rip < base + msize else ""
        print("  0x%016X  %-46s%s" % (base, short, mark))
